// Regenerates src/twPalette.ts from effect-motion's own Tailwind palette.
//
// The palette is checked in rather than imported at runtime so the editor
// integration keeps a tiny dependency footprint (chroma-js only) instead of
// pulling `effect` and the Schema runtime into an extension bundle.
// test/colors.test.ts compares the checked-in table against Color.twMap, so
// drift is a failing test rather than a silently stale swatch.
//
// Usage: pnpm --filter @effect-motion/ide sync:palette  (needs a built core)

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as Color from "effect-motion/Color";

const rows = Object.entries(Color.twMap)
	.map(([name, shades]) => {
		const body = Object.entries(shades)
			.map(([shade, color]) => {
				const r = Math.round(color["~r"]);
				const g = Math.round(color["~g"]);
				const b = Math.round(color["~b"]);
				return `\t\t"${shade}": [${r}, ${g}, ${b}],`;
			})
			.join("\n");
		return `\t${name}: {\n${body}\n\t},`;
	})
	.join("\n");

const file = `// GENERATED by scripts/sync-tw-palette.mjs — do not edit by hand.
// Run \`pnpm --filter @effect-motion/ide sync:palette\` to refresh, and see
// test/colors.test.ts, which fails when this drifts from Color.twMap.

/** A palette entry's clamped 8-bit channels. */
export type TwRgb = readonly [r: number, g: number, b: number];

/** effect-motion's Tailwind palette, flattened to 8-bit channels. */
export const twPalette = {
${rows}
} as const satisfies Record<string, Record<string, TwRgb>>;

/** Every Tailwind colour name \`Color.tw\` accepts. */
export type TwColorName = keyof typeof twPalette;

/** Every shade key, shared by every colour. */
export type TwShade = keyof (typeof twPalette)[TwColorName];
`;

const out = fileURLToPath(new URL("../src/twPalette.ts", import.meta.url));
writeFileSync(out, file);
console.log(`wrote ${out}`);
